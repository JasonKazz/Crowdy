/* Run from backend/: node tests/editor_geometry.test.cjs */
const assert = require('node:assert/strict');
const G = require('../app/simulation/editor-geometry.js');
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-9, `${a} != ${b}`);
const rectangle=[[2,3],[5,3],[5,5],[2,5]];
const moved=G.translate(rectangle,1,-2);
assert.deepEqual(moved,[[3,1],[6,1],[6,3],[3,3]]);
assert.deepEqual(rectangle,[[2,3],[5,3],[5,5],[2,5]]);
const rotated=G.rotate(rectangle,90),r=G.bounds(rotated);
close(r.maxX-r.minX,2);close(r.maxY-r.minY,3);
const resized=G.bounds(G.resize(rectangle,6,4));
close(resized.maxX-resized.minX,6);close(resized.maxY-resized.minY,4);
assert.throws(()=>G.resize(rectangle,0,1));
const wall={id:'w',start:[8,0],end:[8,10],thickness:.2};
const door={id:'d',wall_id:'w',offset:4,width:1.2};
const pieces=G.wallPieces(wall,[door]);
assert.equal(pieces.length,2);
close(G.bounds(pieces[0]).maxY,3.4);close(G.bounds(pieces[1]).minY,4.6);
close(G.doorOffset(wall,door,[20,6]),6);
close(G.doorOffset(wall,door,[8,-10]),.6);
close(G.doorOffset(wall,door,[8,20]),9.4);
const angled={id:'a',start:[2,2],end:[5,6],thickness:.4};
close(G.wallLength(angled),5);
close(G.doorOffset(angled,{offset:1,width:1},[3.5,4]),2.5);
const shifted={...wall,start:[7,0],end:[7,10]};
const opening=G.bounds(G.wallPolygon(shifted,3.4,4.6));
close(opening.minX,6.9);close(opening.maxX,7.1);close(opening.minY,3.4);
const floor={id:'floor',polygon:[[0,0],[10,0],[10,8],[0,8]]};
const exit={id:'east',floor_id:'floor',edge_index:1,offset:4,width:1.2,landing_depth:2};
const exterior=G.exitGeometry(exit,[floor]);
close(G.bounds(exterior.apron).minX,9.95);close(G.bounds(exterior.apron).maxX,12);
close(G.bounds(exterior.target).minX,10.22);close(G.bounds(exterior.target).maxX,10.4);
close(G.bounds(exterior.threshold).minY,3.4);close(G.bounds(exterior.threshold).maxY,4.6);
close(G.doorOffset(exterior.wall,exit,[20,6]),6);
const reversed=G.bounds(G.exitGeometry(exit,[{...floor,polygon:[...floor.polygon].reverse()}]).apron);
for(const key of Object.keys(reversed))close(reversed[key],G.bounds(exterior.apron)[key]);
console.log('Editor geometry checks passed: whole-object moves, wall cuts, attached doors, and outside exit geometry.');
// Resizing keeps the opposite corner fixed and transforms every vertex.
const corner=G.resizeCorner(rectangle,2,[8,7]);
assert.deepEqual(corner,[[2,3],[8,3],[8,7],[2,7]]);
const proportional=G.bounds(G.resizeCorner(rectangle,2,[8,6],true));
close((proportional.maxX-proportional.minX)/(proportional.maxY-proportional.minY),1.5);
assert.deepEqual(rectangle,[[2,3],[5,3],[5,5],[2,5]]);
const attachment=G.nearestEdge([floor],[12,6],1.2);
assert.equal(attachment.edge_index,1);close(attachment.offset,6);
assert.equal(G.nearestEdge([floor],[5,-1],1.2).edge_index,0);
assert.deepEqual(G.zoomBox([0,0,20,10],.5,[5,5]),[2.5,2.5,10,5]);
const open=G.exitGeometry(exit,[floor]),corridor=G.exitGeometry({...exit,outside_space:'corridor'},[floor]);
assert.ok(G.bounds(open.apron).maxY>G.bounds(corridor.apron).maxY+1);
assert.deepEqual(open.target,corridor.target);
assert.deepEqual(G.exitGeometry({...exit,landing_depth:6},[floor]).target,open.target);
close(G.bounds(G.exitGeometry(exit,[floor],.35).target).minX,10.37);
console.log('Canvas tool checks passed: anchored resizing, aspect ratio, boundary attachment, zoom, and open/corridor discharge.');
